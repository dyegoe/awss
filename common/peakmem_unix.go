package common

import "syscall"

// PeakMemory returns the most memory the process has held, in bytes: the maximum resident set
// size the OS charges it, not only the Go heap. It returns false when the OS does not report it.
func PeakMemory() (int64, bool) {
	var ru syscall.Rusage
	if err := syscall.Getrusage(syscall.RUSAGE_SELF, &ru); err != nil {
		return 0, false
	}
	return maxRSSBytes(ru.Maxrss), true
}
