// TestGenerate checks the docs of a fixture module: the first sentence without the field name and
// its verb, one entry per name of a shared line, and no entry for a field without a comment or a
// `json` tag, a field left out of the JSON output, or a type of a test file or testdata directory.
func TestGenerate(t *testing.T) {
	got, err := Generate("testdata", "fixture")
	if err != nil {
		t.Fatalf("Generate(testdata) error = %v", err)
	}
	want := `// Code generated by internal/fielddoc; DO NOT EDIT.

package fixture

// fieldDocs maps "<package path>.<type>.<field>" to the first sentence of the field's
// doc comment, for the Fields section of --help. Run ` + "`go generate ./cmd`" + ` after changing one.
var fieldDocs = map[string]string{
	"example.com/fixture/search/row.dataRow.A":      "A and B share a line.",
	"example.com/fixture/search/row.dataRow.B":      "A and B share a line.",
	"example.com/fixture/search/row.dataRow.Free":   "Free text that does not start with the field name.",
	"example.com/fixture/search/row.dataRow.ID":     "The ID of the row.",
	"example.com/fixture/search/row.dataRow.Names":  "The names of the row, e.g. a and b.",
	"example.com/fixture/search/row.dataRow.Public": "Whether the row is public.",
	"example.com/fixture/search/row.dataRow.Size":   "1.5 GB or more, on two lines.",
}
`
	if string(got) != want {
		t.Errorf("Generate(testdata) =\n%s\nwant\n%s", got, want)
	}
}

// TestGenerate_repository checks cmd/fielddocs_gen.go is what `go generate ./cmd` writes now: a
// field comment changed without running it fails here.
func TestGenerate_repository(t *testing.T) {
	want, err := Generate("../..", "cmd")
	if err != nil {
		t.Fatalf("Generate(module) error = %v", err)
	}
	got, err := os.ReadFile("../../cmd/fielddocs_gen.go")
	if err != nil {
		t.Fatalf("reading cmd/fielddocs_gen.go: %v", err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("cmd/fielddocs_gen.go is stale: run go generate ./cmd")
	}
}

// TestGenerate_errors checks a module root with no go.mod, no module line or a file that does not
// parse is an error.
func TestGenerate_errors(t *testing.T) {
	tests := []struct {
		name string
		root string
		want string
	}{
		{name: "no go.mod", root: "testdata/search", want: "reading go.mod"},
		{name: "no module line", root: "testdata/nomodule", want: "no module line"},
		{name: "parse error", root: "testdata/broken", want: "parsing"},
		{name: "no root", root: "testdata/missing", want: "reading go.mod"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, err := Generate(tt.root, "cmd")
			if err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Errorf("Generate(%s) error = %v, want one with %q", tt.root, err, tt.want)
			}
		})
	}
}

// TestRun checks run writes the source Generate returns, and reports a file it cannot write.
func TestRun(t *testing.T) {
	out := filepath.Join(t.TempDir(), "docs_gen.go")
	if err := run("testdata", out, "fixture"); err != nil {
		t.Fatalf("run(testdata) error = %v", err)
	}
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatalf("reading %s: %v", out, err)
	}
	want, err := Generate("testdata", "fixture")
	if err != nil {
		t.Fatalf("Generate(testdata) error = %v", err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("run(testdata) wrote\n%s\nwant\n%s", got, want)
	}

	if err := run("testdata", filepath.Join(t.TempDir(), "no", "dir.go"), "fixture"); err == nil {
		t.Errorf("run(testdata, missing dir) error = nil, want an error")
	}
	if err := run("testdata/broken", out, "fixture"); err == nil {
		t.Errorf("run(testdata/broken) error = nil, want an error")
	}
}

// TestRender checks a package name that is not Go is a formatting error.
func TestRender(t *testing.T) {
	if _, err := render("not go", map[string]string{}); err == nil {
		t.Errorf("render(\"not go\") error = nil, want an error")
	}
}

// TestFirstSentence checks where the first sentence ends.
func TestFirstSentence(t *testing.T) {
	tests := []struct {
		name string
		text string
		want string
	}{
		{name: "two sentences", text: "One. Two.", want: "One."},
		{name: "abbreviation", text: "Such as e.g. this. Next.", want: "Such as e.g. this."},
		{name: "number", text: "Is 1.5 GB.", want: "Is 1.5 GB."},
		{name: "back quote", text: "One. `two` next.", want: "One."},
		{name: "one sentence", text: "Only one", want: "Only one"},
		{name: "empty", text: "", want: ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := firstSentence(tt.text); got != tt.want {
				t.Errorf("firstSentence(%q) = %q, want %q", tt.text, got, tt.want)
			}
		})
	}
}
